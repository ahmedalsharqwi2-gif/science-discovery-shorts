import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {createServer} from 'vite';
import {chromium} from 'playwright';
import {bundle} from '@remotion/bundler';
import {selectComposition, renderMedia} from '@remotion/renderer';
await fs.mkdir('output',{recursive:true});
const executablePath=process.env.TOOLKIT_CHROME || chromium.executablePath();
const server=await createServer({configFile:'vite.config.ts',server:{port:4173,strictPort:true}});
await server.listen();
const browser=await chromium.launch({executablePath,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
try {
 const page=await browser.newPage({viewport:{width:540,height:960}});
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 await page.goto('http://127.0.0.1:4173');
 await page.waitForFunction(()=>window.toolkit?.ready===true);
 await page.evaluate(()=>window.toolkit.seek(0));
 await page.screenshot({path:'output/effects-start.png'});
 await page.evaluate(()=>window.toolkit.seek(1.8));
 await page.screenshot({path:'output/effects-end.png'});
 assert.equal(errors.length,0,errors.join('\n'));
 const a=await fs.readFile('output/effects-start.png'),b=await fs.readFile('output/effects-end.png');
 assert(!a.equals(b),'Seeking must change the rendered image');
} finally {await browser.close();await server.close();}
const serveUrl=await bundle({entryPoint:path.resolve('src/video.tsx')});
const options={serveUrl,id:'ToolkitCheck',browserExecutable:executablePath,chromiumOptions:{gl:'swangle'}};
const composition=await selectComposition(options);
await renderMedia({...options,composition,codec:'h264',outputLocation:'output/toolkit-check.mp4',concurrency:1});
const metadata=JSON.parse(execFileSync('ffprobe',['-v','error','-show_streams','-show_format','-of','json','output/toolkit-check.mp4'],{encoding:'utf8'}));
const video=metadata.streams.find(s=>s.codec_type==='video');
assert.equal(video.width,540);assert.equal(video.height,960);assert.equal(video.r_frame_rate,'30/1');assert(Math.abs(Number(metadata.format.duration)-2)<0.1);
execFileSync('ffmpeg',['-v','error','-i','output/toolkit-check.mp4','-f','null','-']);
await fs.writeFile('output/verification.json',JSON.stringify({verified:true,motionCanvasBuild:true,pixiGsapThreeBrowser:true,remotionRender:true,width:540,height:960,fps:30,duration:2,productionPipelineIntegrated:false},null,2));
console.log('Verified Motion Canvas build, PixiJS/GSAP/Three browser frames, and Remotion MP4 export.');
