"""Deliver actual verified review files on an isolated download-only branch."""
import hashlib,json,os,subprocess
from pathlib import Path
root=Path('professional_motion/output')
report=json.loads((root/'verification.json').read_text())
if report.get('visual_gate',{}).get('passed') is not True or report.get('audio_tail',{}).get('audio_tail_checked') is not True:raise ValueError('Only verified final media may be delivered')
video=root/'professional-review.mp4'
subprocess.run(['ffmpeg','-v','error','-i',str(video),'-f','null','-'],check=True)
out=Path('review_download');out.mkdir(exist_ok=True)
subprocess.run(['ffmpeg','-v','error','-y','-i',str(video),'-vf','scale=720:1280','-c:v','libx264','-preset','fast','-crf','24','-c:a','aac','-b:a','160k','-movflags','+faststart',str(out/'review-720p.mp4')],check=True)
branch='codex/professional-video-'+os.environ['GITHUB_RUN_ID']
base='https://github.com/'+os.environ['GITHUB_REPOSITORY']+'/raw/refs/heads/'+branch+'/'
(out/'README.md').write_text('# Verified '+report['profile']+' review\n\n[Watch / download 720p]('+base+'review-720p.mp4)\n\n[Download 1080p]('+base+'review-1080p.mp4)\n\nSHA256 of full review: '+hashlib.sha256(video.read_bytes()).hexdigest()+'\n\nGenerated by this repository. Review delivery is separate from social publication.\n')
def git(*args,data=None):return subprocess.check_output(['git',*args],input=data).decode().strip()
files={'review-1080p.mp4':video,'review-720p.mp4':out/'review-720p.mp4','verification.json':root/'verification.json','README.md':out/'README.md'}
entries=[]
for name,path in files.items():entries.append('100644 blob '+git('hash-object','-w',str(path))+'\t'+name+'\n')
tree=git('mktree',data=''.join(entries).encode());commit=git('-c','user.name=review-delivery-bot','-c','user.email=bot@users.noreply.github.com','commit-tree',tree,'-m','Verified '+report['profile']+' review media [skip ci]')
git('push','origin',commit+':refs/heads/'+branch)
if os.getenv('GITHUB_STEP_SUMMARY'):
 with open(os.environ['GITHUB_STEP_SUMMARY'],'a') as f:f.write('### Actual review video\n\n[Watch 720p]('+base+'review-720p.mp4) · [Download 1080p]('+base+'review-1080p.mp4)\n')
print(base+'review-720p.mp4')
